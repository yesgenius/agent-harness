/**
 * @file Generates the navigation index agents read before opening a specification.
 *
 * Each specification gets a table of its sections with line ranges, so an agent reads one
 * section instead of the whole file.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { loadConfig } from './lib/config.js';
import { isMain } from './lib/entry.js';
import { assertFloor, walkFiles } from './lib/scan.js';

const SPEC_EXTENSIONS = ['.md'];
const HEADING = /^(#{1,3}) (.+)$/;
const FENCE = /^```/;
const SPEC_FLOOR = 1;
const INDEX_PREFIX = 'index_';
const README = 'README.md';
const GENERATED_NOTICE = '<!-- Generated by scripts/llm-context-map.js. Do not edit. -->';

/**
 * Lists the headings of a Markdown document with their line ranges.
 * @param {string} text Document text.
 * @returns {{title: string, start: number, end: number}[]} Sections in document order.
 */
export function readSections(text) {
  const lines = text.split('\n');
  const sections = [];
  let insideFence = false;
  lines.forEach((line, index) => {
    if (FENCE.test(line)) insideFence = !insideFence;
    const heading = insideFence ? null : HEADING.exec(line);
    if (!heading) return;
    if (sections.length > 0) sections.at(-1).end = index;
    sections.push({ title: heading[2], start: index + 1, end: lines.length });
  });
  return sections;
}

/**
 * Renders every generated index without writing it, so the guard compares the same output.
 * @param {string} root Repository root.
 * @returns {Map<string, string>} Generated path to content.
 */
export function renderIndexes(root = process.cwd()) {
  const { specsDir, indexDir } = loadConfig(root);
  const specs = walkFiles(root, [specsDir], SPEC_EXTENSIONS);
  assertFloor(specs.length, SPEC_FLOOR, 'specifications');
  const rendered = new Map();
  const rows = [];
  for (const spec of specs) {
    const name = basename(spec, SPEC_EXTENSIONS[0]);
    const sections = readSections(readFileSync(join(root, spec), 'utf8'));
    const table = sections.map((section, index) => `| ${index + 1} | ${section.title} | ${section.start}-${section.end} |`);
    const indexName = `${INDEX_PREFIX}${name}.md`;
    rendered.set(`${indexDir}/${indexName}`, [
      GENERATED_NOTICE, '', `# ${spec}`, '', '| # | Section | Lines |', '| --- | --- | --- |', ...table, '',
    ].join('\n'));
    rows.push(`| \`${spec}\` | \`${indexDir}/${indexName}\` | ${sections[0]?.title ?? ''} |`);
  }
  rendered.set(`${indexDir}/${README}`, [
    GENERATED_NOTICE, '', '# Specification map', '',
    'Find the specification here, its section in the index, and read only that section.', '',
    '| Specification | Index | Title |', '| --- | --- | --- |', ...rows, '',
  ].join('\n'));
  return rendered;
}

if (isMain(import.meta)) {
  const root = process.cwd();
  const rendered = renderIndexes(root);
  for (const [path, content] of rendered) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  process.stdout.write(`docs:index: ${rendered.size} files written\n`);
}
