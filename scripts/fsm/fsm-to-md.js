/**
 * @file Generates the human document of each process model. The model is the source; the
 * document is never edited by hand.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadModels } from './model.js';

const GENERATED_NOTICE = '<!-- Generated by scripts/fsm/fsm-to-md.js from the process model. Do not edit. -->';

/**
 * Renders one model as Markdown.
 * @param {object} model Process model.
 * @returns {string} Document text.
 */
export function renderModel(model) {
  const states = model.states.map(({ id, meaning, terminal, durable }) =>
    `| \`${id}\` | ${meaning} | ${terminal ? 'да' : ''} | ${durable ? 'да' : ''} |`);
  const transitions = model.transitions.map(({ id, from, to, when, irreversible }) =>
    `| \`${id}\` | \`${from}\` | \`${to}\` | ${when} | ${irreversible ? 'да' : ''} |`);
  return [
    GENERATED_NOTICE, '', `# ${model.title}`, '', model.purpose, '',
    '## Состояния', '', '| Состояние | Что значит | Конечное | Записано надёжно |', '| --- | --- | --- | --- |', ...states, '',
    '## Переходы', '', '| Переход | Откуда | Куда | Когда | Необратимый |', '| --- | --- | --- | --- | --- |', ...transitions, '',
  ].join('\n');
}

const root = process.cwd();
for (const { entry, model } of loadModels(root)) {
  writeFileSync(join(root, entry.doc), renderModel(model));
  process.stdout.write(`fsm:doc: ${entry.doc}\n`);
}
